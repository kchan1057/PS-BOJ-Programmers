WITH SUM_SCORE AS (
    SELECT E.EMP_NO, SUM(SCORE) AS TOTAL_SCORE
    FROM HR_EMPLOYEES E JOIN HR_GRADE G ON E.EMP_NO = G.EMP_NO
    GROUP BY E.EMP_NO
),
A AS (
    SELECT S.TOTAL_SCORE, S.EMP_NO, E.EMP_NAME, E.POSITION, E.EMAIL, 
    RANK() OVER (
        ORDER BY S.TOTAL_SCORE DESC
    ) AS RNK
    FROM HR_DEPARTMENT D JOIN HR_EMPLOYEES E ON D.DEPT_ID = E.DEPT_ID JOIN SUM_SCORE S ON E.EMP_NO = S.EMP_NO
)

SELECT TOTAL_SCORE, EMP_NO, EMP_NAME, POSITION, EMAIL
FROM A
WHERE RNK = 1