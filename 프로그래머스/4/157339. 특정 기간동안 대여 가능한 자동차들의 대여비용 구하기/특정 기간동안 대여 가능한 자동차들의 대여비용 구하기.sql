WITH AVAILABILITY AS (
    SELECT C.CAR_ID, C.CAR_TYPE, C.DAILY_FEE, 
    CASE
        WHEN START_DATE <= '2022-11-30' AND END_DATE >= '2022-11-01' THEN FALSE
        ELSE TRUE
    END AS AVAIL
    FROM CAR_RENTAL_COMPANY_CAR C LEFT OUTER JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY H ON C.CAR_ID = H.CAR_ID
    WHERE C.CAR_TYPE IN ('세단', 'SUV')
),
RATE AS (
    SELECT CAR_TYPE, DISCOUNT_RATE
    FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN
    WHERE DURATION_TYPE = '30일 이상' AND CAR_TYPE IN ('세단', 'SUV')
),
FIN AS (
    SELECT DISTINCT(CAR_ID), CAR_TYPE, DAILY_FEE,
    CASE
        WHEN MIN(AVAIL) = 0 THEN FALSE
        ELSE TRUE
    END FIN_AVAIL
    FROM AVAILABILITY
    GROUP BY CAR_ID
)

SELECT F.CAR_ID, F.CAR_TYPE, F.DAILY_FEE*(1.00 - R.DISCOUNT_RATE*0.01)*30 AS FEE
FROM FIN F JOIN RATE R ON F.CAR_TYPE = R.CAR_TYPE
WHERE F.FIN_AVAIL = 1 AND (F.DAILY_FEE*(1.00 - R.DISCOUNT_RATE*0.01)*30 >= 500000 AND F.DAILY_FEE*(1.00 - R.DISCOUNT_RATE*0.01)*30 < 2000000)
ORDER BY FEE DESC, F.CAR_TYPE ASC, CAR_ID DESC; 